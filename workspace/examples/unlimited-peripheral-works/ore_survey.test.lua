-- Runs ore_survey.lua against ore_survey.world.json (Minecraft 1.20.1), then calls every method of every
-- UnlimitedPeripheralWorks peripheral in that world: the happy path and the argument errors.

local printed = {}
local realPrint = print
_G.print = function(...)
  local parts = table.pack(...)
  for i = 1, parts.n do parts[i] = tostring(parts[i]) end
  printed[#printed + 1] = table.concat(parts, "\t")
end
shell.run("examples/unlimited-peripheral-works/ore_survey.lua")
_G.print = realPrint
local output = table.concat(printed, "\n")

local simCount = 0
local function sim(command)
  simCount = simCount + 1
  os.queueEvent("ccsim_cmd", ("sim:%d:%.0f"):format(simCount, os.epoch("utc")), textutils.serializeJSON(command))
  sleep(0.1)
end

local function err(fn, ...)
  local ok, e = pcall(fn, ...)
  if ok then error("expected an error but the call succeeded", 2) end
  return (tostring(e):gsub("^[^:]*:%d+: ", ""))
end

