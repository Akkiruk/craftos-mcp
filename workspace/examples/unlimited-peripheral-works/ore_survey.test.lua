  ccunit.eq(err(scanner.scan, "block", 0), "radius should be between 1 and 24")
  ccunit.eq(err(scanner.scan, "fluid", 4), "There is no scanning method fluid")
  waitCooldown(scanner, "stationaryUniversalScan")
  ccunit.eq(err(scanner.scan, "block", 2, "minecraft:not_a_block"), "There is no item minecraft:not_a_block")
  ccunit.eq(err(scanner.scan, "block", 2, true), "Block query should be string or table")
  ccunit.eq(err(scanner.getCooldown), "bad argument #1 (string expected, got nil)")
end)

ccunit.test("ultimate sensor: every analyzer and inspector", function()
  ccunit.eq(sensor.listAnalyzers(), { "dimension" })
  ccunit.eq(sensor.listInspectors(), { "dimension", "biome", "weather", "orientation", "time", "light", "calendar", "chunk" })
  ccunit.eq(sensor.analyze("dimension"), { "minecraft:overworld", "minecraft:the_nether", "minecraft:the_end" })
  ccunit.eq(sensor.inspect("dimension"), "minecraft:overworld")
  ccunit.eq(sensor.inspect("biome"), "minecraft:plains")
  ccunit.eq(sensor.inspect("weather"), "stable")
  ccunit.eq(sensor.inspect("orientation"), 0)
  ccunit.truthy(sensor.inspect("time") >= 1000, "time")
  ccunit.eq(sensor.inspect("light"), { light = 0, sunlight = 15 })
  ccunit.eq(sensor.inspect("calendar"), { day = 0, moonPhase = "Full moon" })
  local before = os.clock()
  ccunit.eq(sensor.inspect("chunk"), { oresDistribution = { ["minecraft:iron_ore"] = 2 }, isSlime = false })
  -- the 10 s cooldown is clock time on a 10x clock: judge what is left by how much of it has gone, which a busy host
  -- makes more than a moment
  local again = { sensor.inspect("chunk") }
  local left, gone = sensor.getCooldown("inspectChunk"), (os.clock() - before) * 1000
  if gone < 10000 then ccunit.eq(again, { nil, "inspectChunk is on cooldown" }) end
  ccunit.truthy(left <= 10000 and left >= 10000 - gone - 100, "cooldown " .. left .. " with " .. gone .. " ms gone")
  ccunit.eq(sensor.getOperations(), { "inspectChunk" })
  ccunit.eq(sensor.getConfiguration().inspectChunk.cooldown, 10000)
  ccunit.eq(err(sensor.analyze, "biome"), "There is no such analyzer")
  ccunit.eq(err(sensor.inspect, "mood"), "There is no such inspector")
  ccunit.eq(err(sensor.inspect), "bad argument #1 (string expected, got nil)")
  sim({ cmd = "upwSetWorld", thundering = true, raining = true })
  ccunit.eq(sensor.inspect("weather"), "thunder")
end)

ccunit.test("item pedestal: an inventory of one slot", function()
  ccunit.eq({ peripheral.getType(itemPedestal) }, { "item_pedestal", "inventory", "inventory_extended" })
  ccunit.eq(itemPedestal.size(), 1)
  ccunit.eq(itemPedestal.list(), {})
  ccunit.eq(itemPedestal.pullItems("chest_0", 1, 2), 2)
  ccunit.eq(itemPedestal.list(), { [1] = { name = "minecraft:diamond", count = 2 } })
  ccunit.eq(itemPedestal.list(true)[1].maxCount, 64)
  ccunit.eq(itemPedestal.list(false, "minecraft:stone"), {})
  ccunit.eq(itemPedestal.getItemDetail(1).name, "minecraft:diamond")
  ccunit.eq(itemPedestal.getItemLimit(1), 64)
  ccunit.eq(itemPedestal.pushItems("chest_0", 1, 1), 1)
  ccunit.eq(itemPedestal.pushItems("chest_0", "minecraft:diamond"), 1)
  ccunit.eq(itemPedestal.list(), {})
  ccunit.eq(itemPedestal.pullItems("chest_0", { name = "minecraft:diamond" }, 5), 3)
  ccunit.eq(itemPedestal.pushItems("chest_0", 1, 0), 0)
  ccunit.eq(itemPedestal.getConfiguration(), { inventoryTransferLimit = 1024, inventoryAPI = { 1, 1 } })
  ccunit.eq(err(itemPedestal.getItemDetail, 2), "slot should be between 1 and 1")
  ccunit.eq(err(itemPedestal.getItemLimit, 0), "slot should be between 1 and 1")
  ccunit.eq(err(itemPedestal.pushItems, "nowhere", 1), "Target 'nowhere' does not exist")
  ccunit.eq(err(itemPedestal.pushItems, "universal_scanner_0", 1), "Target 'universal_scanner_0' is not an inventory")
  ccunit.eq(err(itemPedestal.pushItems, "chest_0", 2), "fromSlot should be between 1 and 1")
  ccunit.eq(err(itemPedestal.pushItems, "chest_0", 1, 1, 28), "toSlot should be between 1 and 27")
  ccunit.eq(err(itemPedestal.pullItems, "nowhere", 1), "Source 'nowhere' does not exist")
  ccunit.eq(err(itemPedestal.pullItems, "chest_0", 30), "fromSlot should be between 1 and 27")
  ccunit.eq(err(itemPedestal.pullItems, "chest_0", 1, "all"), "bad argument #3 (number expected, got string)")
  ccunit.eq(itemPedestal.pushItems("chest_0", 1), 3)
end)

