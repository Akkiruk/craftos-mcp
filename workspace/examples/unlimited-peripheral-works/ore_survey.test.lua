local lectern = peripheral.wrap("minecraft:lectern_0")

local function waitCooldown(p, op)
  local left = p.getCooldown(op)
  if left > 0 then sleep(left / 1000 + 0.05) end
end

ccunit.test("the survey lists the ores and shows the most common one", function()
  ccunit.truthy(output:find("Coal Ore", 1, true), output)
  ccunit.truthy(output:find("Most common: minecraft:iron_ore (2)", 1, true), output)
  ccunit.truthy(output:find("Watch out: 1 mob(s) nearby", 1, true), output)
  ccunit.truthy(output:find("Survey done on day 0, weather stable", 1, true), output)
  local shown = display.getItem()
  ccunit.eq(shown.name, "minecraft:iron_ore")
  ccunit.eq(shown.displayName, "Most common ore")
  ccunit.eq(shown.rawNBT, { display = { Name = '{"text":"Most common ore"}' } })
  ccunit.truthy(type(shown.nbt) == "string" and #shown.nbt == 32, tostring(shown.nbt))
end)

