ccunit.test("universal scanner: blocks, relative to an east-facing scanner", function()
  waitCooldown(scanner, "stationaryUniversalScan")
  local before = os.clock()
  local found = scanner.scan("block", 8, "minecraft:diamond_ore")
  ccunit.eq(#found, 1)
  ccunit.eq({ found[1].x, found[1].y, found[1].z }, { 1, -8, -3 })
  ccunit.eq(found[1].displayName, "Diamond Ore")
  ccunit.truthy(found[1].tags["forge:ores"], "tags")
  -- straight away again: the scanner is cooling down. The cooldown is clock time, and this file runs on a 10x clock,
  -- so a busy host can take the whole 500 ms (50 ms of real time) between the two calls: then the scan is allowed.
  -- The cooldown starts somewhere in the first call, and the second checks it somewhere in its own call: only when the
  -- whole of both fits in the 500 ms is a refusal certain. Past that either answer can be right.
  local none, why = scanner.scan("block", 8)
  if os.clock() - before < 0.5 then
    ccunit.eq(none, nil)
    ccunit.eq(why, "stationaryUniversalScan is on cooldown")
  else
    ccunit.truthy(none == nil or type(none) == "table", tostring(none))
  end
  -- what is left of the 500 ms (a loaded host may already have run past it)
  local left = scanner.getCooldown("stationaryUniversalScan")
  ccunit.truthy(left >= 0 and left <= 500, "cooldown " .. left)
  ccunit.eq({ scanner.getCooldown("nope") }, { nil, "Cannot find this operation" })
  waitCooldown(scanner, "stationaryUniversalScan")
  -- radius 3 reaches down to the grass at y=60: a 7x7 layer of it
  local all = scanner.scan("block", 3, { name = { ["in"] = { "minecraft:grass_block", "minecraft:stone" } } })
  ccunit.eq(#all, 49)
  ccunit.eq({ all[1].name, all[1].y }, { "minecraft:grass_block", -3 })
end)

