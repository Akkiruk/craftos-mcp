end)

ccunit.test("universal scanner: argument errors", function()
  ccunit.eq(err(scanner.scan), "bad argument #1 (string expected, got nil)")
  ccunit.eq(err(scanner.scan, "block", "far"), "bad argument #2 (number expected, got string)")
