ccunit.test("lectern", function()
  ccunit.eq(lectern.hasBook(), true)
  ccunit.eq(lectern.isBookEditable(), false)
  ccunit.eq(lectern.getPageCount(), 2)
  ccunit.eq(lectern.getActivePage(), 1)
  ccunit.eq(lectern.getText(), { "Iron at y=58", "plain" })
  -- the event comes while the call waits for its server tick, so the caller itself never sees it: another coroutine does
  local function heard(event, call)
    local got
    parallel.waitForAll(call, function() got = { os.pullEvent(event) } end)
    return got
  end
  ccunit.eq(heard("lectern_page_changed", function() lectern.setActivePage(2) end), { "lectern_page_changed", 2 })
  ccunit.eq(lectern.getActivePage(), 2)
  ccunit.eq(err(lectern.addPage, "more"), "Book should be editable")
  ccunit.eq(err(lectern.setActivePage, 3), "page should be between 1 and 2")
  ccunit.eq(err(lectern.injectBook, "chest_0"), "Lectern shouldn't contain book")
  ccunit.eq(heard("lectern_book_removed", function() ccunit.eq(lectern.ejectBook("chest_0"), true) end), { "lectern_book_removed" })
  ccunit.eq(lectern.hasBook(), false)
  ccunit.eq(err(lectern.getPageCount), "Lectern should contain book")
  ccunit.eq(err(lectern.ejectBook, "chest_0"), "Lectern should contain book")
  ccunit.eq(heard("lectern_book_changed", function()
    ccunit.eq(lectern.injectBook("chest_0", "minecraft:writable_book"), true)
  end), { "lectern_book_changed", "Book and Quill" })
  ccunit.eq(lectern.isBookEditable(), true)
  ccunit.eq(lectern.getText(), { "first page", "second page" })
  ccunit.eq(lectern.addPage("third"), true)
  ccunit.eq(lectern.editPage(1, "changed"), true)
  ccunit.eq(lectern.removePage(2), true)
  ccunit.eq(lectern.getText(), { "changed", "third" })
  ccunit.eq(lectern.addPage(), true)
  ccunit.eq(lectern.getPageCount(), 3)
  ccunit.eq(err(lectern.editPage, 4, "x"), "page should be between 1 and 3")
  ccunit.eq(err(lectern.removePage, 0), "page should be between 1 and 3")
  ccunit.eq(err(lectern.editPage, 1), "bad argument #2 (string expected, got nil)")
  sim({ cmd = "upwTurnPage", peripheral = "minecraft:lectern_0", page = 3 })
  ccunit.eq(lectern.getActivePage(), 3)
end)
