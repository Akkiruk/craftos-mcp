// Build the instruction files coding agents read (AGENTS.md, the cc-tweaked-dev skill for Codex, Copilot and Claude
// Code, Copilot's instructions, a Cursor rule, GEMINI.md) from one source, scripts/agent-docs/*.md, so they never
// drift apart. Each target is a list of those parts under its own header; the output is formatted with the repo's
// prettier, so `prettier --check .` agrees with it.
//
//   node scripts/build-agent-docs.mjs [--check] [--out <dir>]
//
// The files go to scripts/public/ in a tree that has one (the public copy gets them at its root from there), else to
// the repo root, as in the public copy itself. --check writes nothing and exits 1 when any file is missing or stale.
// The VS Code extension's esbuild.mjs imports TARGETS and forWorkspace to bundle the same files.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
