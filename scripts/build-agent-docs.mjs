/** Where the files go: scripts/public/ in the private tree, the root of the public copy. */
export function defaultOutDir(root = ROOT) {
  const overlay = join(root, "scripts", "public");
  return existsSync(overlay) ? overlay : root;
}

function part(name, target) {
  let text = readFileSync(join(SOURCE, `${name}.md`), "utf8")
    .replace(/\r\n/g, "\n")
    .trim();
  if (text.includes("{{guide}}")) {
    if (!target.guide)
      throw new Error(`${target.path}: part ${name} needs a guide`);
    text = text.replaceAll("{{guide}}", target.guide);
  }
  if (name === "repo") text = `${REPO_START}\n\n${text}\n\n${REPO_END}`;
  return text;
}

let prettier;
async function format(text, path) {
  if (!prettier) {
    const require = createRequire(join(ROOT, "package.json"));
    let entry;
    try {
      entry = require.resolve("prettier");
    } catch {
      throw new Error(
        `no prettier in ${join(ROOT, "node_modules")}: run npm ci at the repo root first`,
      );
    }
    const loaded = await import(pathToFileURL(entry).href);
    prettier = loaded.format ? loaded : loaded.default;
  }
  const file = join(ROOT, path.replace(/\.mdc$/, ".md"));
  const options = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(text, { ...options, parser: "markdown" });
}

/** One target's file, formatted. */
export async function render(target) {
  const blocks = [
    ...(target.front ? [target.front] : []),
    NOTE,
    `# ${target.title}`,
    ...target.parts.map((name) => part(name, target)),
  ];
  return format(`${blocks.join("\n\n")}\n`, target.path);
}

/**
 * A generated file as it goes into someone's own project: without the note about this script and without the part
 * about working on craftos-mcp itself.
 */
export function forWorkspace(text) {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const kept = [];
  let skipping = false;
  for (const line of lines) {
    if (line.trim() === REPO_START) skipping = true;
    else if (line.trim() === REPO_END) skipping = false;
    else if (!skipping && line.trim() !== NOTE) kept.push(line);
  }
  return `${kept
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd()}\n`;
}

async function main(argv) {
  const check = argv.includes("--check");
  const at = argv.indexOf("--out");
  const out = at >= 0 ? resolve(argv[at + 1] ?? ".") : defaultOutDir();
  const stale = [];
  for (const target of TARGETS) {
    const file = join(out, target.path);
    const want = await render(target);
    const have = existsSync(file)
      ? readFileSync(file, "utf8").replace(/\r\n/g, "\n")
      : undefined;
    if (have === want) continue;
    stale.push(target.path);
    if (!check) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, want);
    }
  }
  if (check) {
    if (stale.length) {
      console.error(
        `agent docs out of date in ${out} (run node scripts/build-agent-docs.mjs):\n  ${stale.join("\n  ")}`,
      );
      process.exit(1);
    }
    console.log(`agent docs up to date (${TARGETS.length} files in ${out})`);
  } else
    console.log(
      stale.length
        ? `wrote ${stale.length} of ${TARGETS.length} agent docs in ${out}: ${stale.join(", ")}`
        : `agent docs already up to date (${TARGETS.length} files in ${out})`,
    );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  await main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
